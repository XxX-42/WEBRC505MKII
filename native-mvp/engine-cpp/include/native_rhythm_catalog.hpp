[[nodiscard]] inline constexpr const NativeRhythmPatternMetadata* nativeRhythmPatternByIndex(
    std::uint16_t oneBasedIndex
 ) noexcept {
    return oneBasedIndex >= 1U && oneBasedIndex <= kNativeRhythmPatternCatalog.size()
        ? &kNativeRhythmPatternCatalog[oneBasedIndex - 1U]
        : nullptr;
}

[[nodiscard]] inline constexpr const NativeRhythmPatternMetadata* nativeRhythmPatternById(
    std::string_view stableId
 ) noexcept {
    for (const auto& metadata : kNativeRhythmPatternCatalog) {
        if (metadata.id == stableId) return &metadata;
    }
    return nullptr;
}

